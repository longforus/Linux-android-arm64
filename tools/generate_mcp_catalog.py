#!/usr/bin/env python3
"""Regenerate native MCP catalog from LuckyStarMcp.py without importing its server."""
import argparse
import ast
import json
from pathlib import Path
from pydantic import TypeAdapter

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('source', type=Path, help='Path to windows/LuckyStarMcp.py')
parser.add_argument('--output', type=Path, help='Override the generated header path')
parser.add_argument('--check', action='store_true', help='Check that the catalog is current without writing')
args = parser.parse_args()
source = args.source
tree = ast.parse(source.read_text())
nodes = [ast.ImportFrom(module='__future__', names=[ast.alias(name='annotations')], level=0)]
for node in tree.body:
    if isinstance(node, ast.ImportFrom) and node.module in ('typing', 'typing_extensions', 'pydantic'):
        nodes.append(node)
    elif isinstance(node, (ast.Assign, ast.AnnAssign)):
        name = node.targets[0].id if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name) else ''
        if name in ('AndroidPid', 'BridgePort', 'PositiveTimeout', 'HexAddress', 'HexRegisterValue', 'ScanValueType', 'ScanResultValueType', 'ScanStartMode', 'ScanRefineMode', 'SavedValueKind', 'PointerMode', 'ViewerFormat', 'BreakpointRecordField', 'Sequence'):
            nodes.append(node)
    elif isinstance(node, ast.ClassDef) and node.name == 'AndroidBreakpointPoint':
        nodes.append(node)
ns = globals()
exec(compile(ast.fix_missing_locations(ast.Module(body=nodes, type_ignores=[])), str(source), 'exec'), ns)
bridge_ops = {'scan_start':'scan.start', 'scan_refine':'scan.refine', 'saved_list':'saved.list', 'saved_add':'saved.add', 'saved_remove':'saved.remove', 'saved_write':'saved.write', 'saved_set_note':'saved.note.set', 'saved_set_locked':'saved.lock.set', 'saved_offset':'saved.offset', 'saved_clear':'saved.clear', 'viewer_open':'viewer.open', 'breakpoint_set':'breakpoint.set'}
entries = []
for fn in tree.body:
    if not isinstance(fn, ast.FunctionDef) or not any(isinstance(d, ast.Call) and isinstance(d.func, ast.Attribute) and d.func.attr == 'tool' for d in fn.decorator_list):
        continue
    if fn.name in ('configure_android_bridge', 'discover_android_bridges'):
        continue
    operation = None
    for call in ast.walk(fn):
        if not isinstance(call, ast.Call): continue
        if isinstance(call.func, ast.Name) and call.func.id in ('_call_bridge_operation', '_start_monitor') and isinstance(call.args[0], ast.Constant):
            operation = call.args[0].value + ('.start' if call.func.id == '_start_monitor' else '')
            break
        if isinstance(call.func, ast.Attribute) and call.func.attr in bridge_ops:
            operation = bridge_ops[call.func.attr]
            break
    assert operation, fn.name
    properties, required = {}, []
    defaults = dict(zip([a.arg for a in fn.args.args][-len(fn.args.defaults):], fn.args.defaults)) if fn.args.defaults else {}
    for arg in fn.args.args:
        annotation = eval(ast.unparse(arg.annotation), ns)
        schema = TypeAdapter(annotation).json_schema()
        defs = schema.pop('$defs', {})
        def resolve(obj):
            if isinstance(obj, dict):
                if '$ref' in obj: return resolve(defs[obj['$ref'].split('/')[-1]])
                return {k: resolve(v) for k, v in obj.items()}
            if isinstance(obj, list): return [resolve(v) for v in obj]
            return obj
        schema = resolve(schema)
        if arg.arg in defaults: schema['default'] = ast.literal_eval(defaults[arg.arg])
        else: required.append(arg.arg)
        properties[arg.arg] = schema
    entries.append({'name':fn.name, 'description':ast.get_docstring(fn), 'inputSchema':{'type':'object', 'properties':properties, 'required':required, 'additionalProperties':False}, 'operation':operation})
native_root = root / ('LS_KTool/jni' if (root / 'LS_KTool/jni').is_dir() else 'android/jni')
output = args.output or native_root / 'include/service/mcp_catalog.h'
content = ('// Generated by tools/generate_mcp_catalog.py; edit the generator/source, then regenerate.\n#pragma once\nnamespace xst_mcp {\ninline const json &Catalog() {\n    static const json catalog = json::parse(R"MCP(' + json.dumps(entries, ensure_ascii=False, indent=2) + ')MCP");\n    return catalog;\n}\n}\n')
if args.check:
    if not output.exists() or output.read_text() != content:
        parser.exit(1, f'Catalog is out of date: {output}\n')
    print(f'Catalog matches {len(entries)} tools: {output}')
else:
    output.write_text(content)
    print(f'Generated {len(entries)} tools: {output}')
